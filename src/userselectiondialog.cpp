#include "db/databasemanager.h"
#include "userselectiondialog.h"
#include "theme.h"

#include <QMouseEvent>
#include <QToolButton>

UserSelectionDialog::UserSelectionDialog(QWidget* parent)
    : QDialog(parent), selectedUserId(-1) {
    ui.setupUi(this);

    Theme::applyTheme(Theme::Type::Dark);

    //setWindowTitle("Select or Create User");
    setWindowFlags(Qt::FramelessWindowHint);

    // Load existing users into the combo box
    loadUsers();

    // Connect signals and slots
    connect(ui.createUserButton, &QToolButton::clicked, this, &UserSelectionDialog::toggleUserCreationWidgets);
    connect(ui.confirmButton, &QToolButton::clicked, this, &UserSelectionDialog::confirmSelection);
    connect(ui.confirmNewUserButton, &QToolButton::clicked, this, &UserSelectionDialog::createUser);
    connect(ui.closeDialogButton, &QToolButton::clicked, this, &QDialog::close);
}

void UserSelectionDialog::mousePressEvent(QMouseEvent *event)  {
    if (event->button() == Qt::LeftButton) {
        mousePressed = true;
        lastMousePosition = event->globalPos() - frameGeometry().topLeft();
        event->accept();
    }
}

void UserSelectionDialog::mouseMoveEvent(QMouseEvent *event) {
    if (mousePressed && event->buttons() & Qt::LeftButton) {
        move(event->globalPos() - lastMousePosition);
        event->accept();
    }
}

void UserSelectionDialog::mouseReleaseEvent(QMouseEvent *event) {
    mousePressed = false;
    event->accept();
}

void UserSelectionDialog::loadUsers() {
    UserDAO userDao;
    ui.userComboBox->clear();

    // Fetch all users and populate the combo box
    QSqlQuery query(DatabaseManager::instance().database());
    if (query.exec("SELECT id, username FROM users")) {
        while (query.next()) {
            int id = query.value("id").toInt();
            QString username = query.value("username").toString();
            ui.userComboBox->addItem(username, id);
        }
    }
}

void UserSelectionDialog::toggleUserCreationWidgets() {
    widgetsVisible = !widgetsVisible;

    // Iterate through all items in the horizontal layout
    for (int i = 0; i < ui.UserCreationQHBoxLayout->count(); ++i) {
        QWidget *widget = ui.UserCreationQHBoxLayout->itemAt(i)->widget();
        if (widget) {
            widget->setVisible(widgetsVisible);
        }
    }
}

void UserSelectionDialog::createUser() {
    QString username = ui.newUsernameInput->text().trimmed();
    QString name = ui.newNameInput->text().trimmed();

    if (username.isEmpty() || name.isEmpty()) {
        QMessageBox::warning(this, "Invalid Input", "Please fill in both name and email.");
        return;
    }

    User newUser(0, username, name); // ID is autogenerated in SQLite
    UserDAO userDao;

    if (userDao.createUser(newUser)) {
        QMessageBox::information(this, "User Created", "New user has been created successfully!");
        loadUsers(); // Reload users to include the newly created one
        ui.userComboBox->setCurrentText(username); // Select the newly created user
    } else {
        QMessageBox::critical(this, "Error", "Failed to create user.");
    }
}

void UserSelectionDialog::confirmSelection() {
    selectedUserId = ui.userComboBox->currentData().toInt();
    if (selectedUserId == -1) {
        QMessageBox::warning(this, "No User Selected", "Please select a user or create a new one.");
        return;
    }
    accept(); // Close dialog and return success
}

int UserSelectionDialog::getSelectedUserId() const {
    return selectedUserId;
}
