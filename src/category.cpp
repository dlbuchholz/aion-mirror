#include "db/databasemanager.h"
#include "category.h"

// Category Implementation
Category::Category(int id, const QString& name, const QString& type)
    : categoryId(id), name(name), type(type) {}

int Category::getCategoryId() const {
    return categoryId;
}

QString Category::getName() const {
    return name;
}

QString Category::getType() const {
    return type;
}

// CategoryDAO Implementation
CategoryDAO::CategoryDAO() {}

int CategoryDAO::addCategory(const Category& category) {
    QSqlQuery query(DatabaseManager::instance().database());
    query.prepare("INSERT INTO categories (name, type) VALUES (:name, :type)");
    query.bindValue(":name", category.getName());
    query.bindValue(":type", category.getType());

    if (!query.exec()) {
        qWarning() << "CategoryDAO::createCategory failed:" << query.lastError().text();
        return -1;  // Return -1 on failure
    }

    return query.lastInsertId().toInt();  // Return the autogenerated ID on success
}

bool CategoryDAO::createCategory(const Category& category) {
    QSqlQuery query(DatabaseManager::instance().database());
    query.prepare("INSERT INTO categories (id, name, type) VALUES (:id, :name, :type)");
    query.bindValue(":id", category.getCategoryId());
    query.bindValue(":name", category.getName());
    query.bindValue(":type", category.getType());

    if (!query.exec()) {
        handleError(query);
        return false;
    }
    return true;
}

QList<Category> CategoryDAO::getAllCategories() {
    QSqlQuery query(DatabaseManager::instance().database());
    query.prepare("SELECT id, name, type FROM categories");

    QList<Category> categories;
    if (query.exec()) {
        while (query.next()) {
            categories.append(Category(
                query.value("id").toInt(),
                query.value("name").toString(),
                query.value("type").toString()
                ));
        }
    } else {
        handleError(query);
    }
    return categories;
}

Category CategoryDAO::getCategoryById(int categoryId) {
    QSqlQuery query(DatabaseManager::instance().database());
    query.prepare("SELECT id, name, type FROM categories WHERE id = :id");
    query.bindValue(":id", categoryId);

    if (query.exec() && query.next()) {
        return Category(
            query.value("id").toInt(),
            query.value("name").toString(),
            query. value("type").toString()
            );
    } else {
        handleError(query);
        return Category(-1, "", "");  // Return empty category on error
    }
}

bool CategoryDAO::editCategory(int id, const QString& newName, const QString& newType) {
    QSqlQuery query(DatabaseManager::instance().database());
    query.prepare("UPDATE categories SET name = :name, type = :type WHERE id = :id");
    query.bindValue(":name", newName);
    query.bindValue(":type", newType);
    query.bindValue(":id", id);

    if (!query.exec()) {
        handleError(query);
        return false;
    }

    return true;
}

bool CategoryDAO::deleteCategory(int categoryId) {
    QSqlQuery query(DatabaseManager::instance().database());
    query.prepare("DELETE FROM categories WHERE id = :id");
    query.bindValue(":id", categoryId);

    if (!query.exec()) {
        handleError(query);
        return false;
    }
    return true;
}

void CategoryDAO::handleError(const QSqlQuery& query) {
    if (query.lastError().isValid()) {
        qDebug() << "SQL Error:" << query.lastError().text();
    }
}
